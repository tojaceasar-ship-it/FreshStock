function detectLanguage(): Language {
  const saved = localStorage.getItem(LANGUAGE_KEY)
  if (saved === 'pl' || saved === 'en' || saved === 'nl') return saved
  const browser = navigator.language.toLowerCase()
  if (browser.startsWith('nl')) return 'nl'
  if (browser.startsWith('en')) return 'en'
  return 'pl'
}

export function getLanguage(): Language {
  if (typeof window === 'undefined') return 'pl'
  return detectLanguage()
}

export function getLocale(language = getLanguage()) {
  return language === 'nl' ? 'nl-NL' : language === 'en' ? 'en-GB' : 'pl-PL'
}

function translateDynamic(value: string, language: Exclude<Language, 'pl'>) {
  const index = language === 'en' ? 0 : 1
  const exact = messages[value]
  if (exact) return exact[index]

  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^(\d+) produktów$/, m => language === 'en' ? `${m[1]} products` : `${m[1]} producten`],
    [/^(\d+) aktywnych$/, m => language === 'en' ? `${m[1]} active` : `${m[1]} actief`],
    [/^(\d+) przetermin\.!$/, m => language === 'en' ? `${m[1]} expired!` : `${m[1]} verlopen!`],
    [/^Dodano (\d+), pominięto (\d+)\.$/, m => language === 'en' ? `Added ${m[1]}, skipped ${m[2]}.` : `${m[1]} toegevoegd, ${m[2]} overgeslagen.`],
    [/^Zsynchronizowano (\d+) zapisów offline$/, m => language === 'en' ? `Synced ${m[1]} offline entries` : `${m[1]} offline-items gesynchroniseerd`],
    [/^Krok (\d+) z 14 · (.+)$/, m => language === 'en' ? `Step ${m[1]} of 14 · ${translateDynamic(m[2], language)}` : `Stap ${m[1]} van 14 · ${translateDynamic(m[2], language)}`],
    [/^Urządzenia: (.+)$/, m => language === 'en' ? `Devices: ${m[1]}` : `Apparaten: ${m[1]}`],
    [/^Sprzedaż (\d+)d$/, m => language === 'en' ? `Sales ${m[1]}d` : `Verkoop ${m[1]}d`],
    [/^Straty (\d+)d$/, m => language === 'en' ? `Waste ${m[1]}d` : `Verlies ${m[1]}d`],
  ]
  for (const [pattern, formatter] of patterns) {
    const match = value.match(pattern)
    if (match) return formatter(match)
  }
  return value
}

export function translate(value: string, language = getLanguage()) {
  if (language === 'pl') return polishOverrides[value] || value
  return translateDynamic(value, language)
}

type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void }
const LanguageContext = createContext<LanguageContextValue | null>(null)

const textState = new WeakMap<Text, { source: string; rendered: string }>()
const attributeState = new WeakMap<Element, Map<string, { source: string; rendered: string }>>()

function localizeTextNode(node: Text, language: Language) {
  if (node.parentElement?.closest('[data-i18n-ignore]')) return
  const current = node.nodeValue || ''
  const state = textState.get(node)
  const source = state && current === state.rendered ? state.source : current
  const trimmed = source.trim()
  if (!trimmed) return
  const translated = translate(trimmed, language)
  const rendered = source.replace(trimmed, translated)
  textState.set(node, { source, rendered })
  if (current !== rendered) node.nodeValue = rendered
}

function localizeAttributes(element: Element, language: Language) {
  if (element.closest('[data-i18n-ignore]')) return
  const names = ['placeholder', 'title', 'aria-label']
  const state = attributeState.get(element) || new Map<string, { source: string; rendered: string }>()
  for (const name of names) {
    const current = element.getAttribute(name)
    if (!current) continue
    const previous = state.get(name)
    const source = previous && current === previous.rendered ? previous.source : current
    const rendered = translate(source, language)
    state.set(name, { source, rendered })
    if (current !== rendered) element.setAttribute(name, rendered)
  }
  attributeState.set(element, state)
}

function localizeTree(root: Node, language: Language) {
  if (root.nodeType === Node.TEXT_NODE) {
    localizeTextNode(root as Text, language)
    return
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return
  const element = root as Element
  localizeAttributes(element, language)
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
  let current: Node | null = walker.nextNode()
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) localizeTextNode(current as Text, language)
    else localizeAttributes(current as Element, language)
    current = walker.nextNode()
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>(() => getLanguage())
  useEffect(() => {
    document.documentElement.lang = language
    localizeTree(document.body, language)
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === 'characterData') localizeTextNode(record.target as Text, language)
        for (const node of record.addedNodes) localizeTree(node, language)
        if (record.type === 'attributes') localizeAttributes(record.target as Element, language)
      }
    })
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
    return () => observer.disconnect()
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: next => {
      localStorage.setItem(LANGUAGE_KEY, next)
      updateLanguage(next)
      window.location.reload()
    },
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}

export function LanguageSwitcher() {
  const { language, setLanguage } = useLanguage()
  return (
    <label data-i18n-ignore className="fixed right-14 top-3 z-[100] rounded-xl border border-gray-200 bg-white/95 px-2 py-1 shadow-sm backdrop-blur lg:right-56">
      <span className="sr-only">Language</span>
      <select
        aria-label="Language"
        value={language}
        onChange={event => setLanguage(event.target.value as Language)}
        className="bg-transparent text-xs font-semibold text-gray-700 outline-none"
      >
        <option value="pl">🇵🇱 Polski</option>
        <option value="en">🇬🇧 English</option>
        <option value="nl">🇳🇱 Nederlands</option>
      </select>
    </label>
  )
}
